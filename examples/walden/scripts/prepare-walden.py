class Node:
    def __init__(self, tag, attrs=()): self.tag, self.attrs, self.children = tag, dict(attrs), []
    def all(self):
        yield self
        for child in self.children:
            if isinstance(child, Node): yield from child.all()

class Parser(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.root = Node('root'); self.stack = [self.root]
    def handle_starttag(self, tag, attrs):
        n=Node(tag,attrs); self.stack[-1].children.append(n)
        if tag not in {'meta','link','br','hr','img'}: self.stack.append(n)
    def handle_endtag(self, tag):
        assert self.stack[-1].tag == tag, ('Unbalanced source', tag)
        self.stack.pop()
    def handle_data(self, data): self.stack[-1].children.append(data)

def text(n):
    if isinstance(n,str): return n
    if n.tag=='br': return '\n'
    return ''.join(text(c) for c in n.children)

def inline(n, fixed=False):
    # HTML ASCII whitespace collapses; NBSPs and explicit breaks remain. Offsets
    # are measured after collapse in UTF-16, matching DOM Range and kit anchors.
    atoms=[]; ranges=[]
    def walk(x, active=()):
        if isinstance(x,str):
            for char in x: atoms.append((char,active))
            return
        assert x.tag in {'p','pre','h1','h2','td','i','b','br','a','span'}, x.tag
        if x.tag=='br': atoms.append(('\n',active)); return
        style={'i':'em','b':'strong'}.get(x.tag)
        if style: active=active+(len(ranges),); ranges.append(style)
        for c in x.children: walk(c,active)
    walk(n)
    if not fixed:
        out=[]; pending=None
        # Explicit br is distinguished from source wrapping before conversion.
        # Re-run with a private sentinel (asserted absent from the source).
        def replace_br(x):
            if isinstance(x,Node):
                if x.tag=='br': x.children=['\ue000']; x.tag='span'
                else:
                    for c in x.children: replace_br(c)
        replace_br(n); atoms=[]; ranges=[]; walk(n)
        for char,active in atoms:
            if char in ' \t\n\r\f':
                if out and out[-1][0]!='\n': pending=(' ',active)
            elif char=='\ue000': out.append(('\n',active)); pending=None
            else:
                if pending: out.append(pending); pending=None
                out.append((char,active))
        atoms=out
    value=''.join(c for c,_ in atoms); marks=[]
    for number,kind in enumerate(ranges):
        offsets=[]; offset=0
        for char,active in atoms:
            width=len(char.encode('utf-16-le'))//2
            if number in active: offsets.extend([offset,offset+width])
            offset+=width
        if offsets: marks.append({'kind':kind,'start':min(offsets),'end':max(offsets)})
    return value,marks

